function Glyph({ kind }: { kind: IntegrationMarkKind }) {
  // Sin «:», que rompe la referencia url(#…) en algunos navegadores.
  const gradientId = `g${useId().replace(/:/g, "")}`;
  if (kind === "api") return <ApiGlyph />;
  if (kind === "keys") return <KeysGlyph />;
  const gradient = kind === "gemini";
  return (
    <svg viewBox="0 0 24 24" aria-hidden="true">
      {gradient && (
        <defs>
          <linearGradient id={gradientId} x1="0" y1="0" x2="1" y2="1">
            <stop offset="0" stopColor="#4285F4" />
            <stop offset="1" stopColor="#9B72CB" />
          </linearGradient>
        </defs>
      )}
      <path d={PATHS[kind]} fill={gradient ? `url(#${gradientId})` : "currentColor"} />
    </svg>
  );
}

export function IntegrationMark({ kind, size = "md" }: { kind: IntegrationMarkKind; size?: "sm" | "md" | "lg" }) {
  return (
    <span className={`integration-mark integration-mark--${kind} integration-mark--${size}`} aria-hidden="true">
      <Glyph kind={kind} />
    </span>
  );
}
